-- FoodBook - esquema de tablas

-- DROP TABLE IF EXISTS FAVORITO, PLATO, TIPO_COCINA, CATEGORIA, USUARIO;

CREATE TABLE USUARIO (
  ID_USUARIO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME VARCHAR(30) NOT NULL UNIQUE,
  EMAIL VARCHAR(120) NOT NULL UNIQUE,
  PASSWORD VARCHAR(100) NOT NULL,
  ROL VARCHAR(10) NOT NULL DEFAULT 'USER',
  FECHA_REGISTRO TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT CHECK_USUARIO_ROL CHECK (ROL IN ('USER', 'ADMIN'))
);

CREATE TABLE CATEGORIA (
  ID_CATEGORIA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE TIPO_COCINA (
  ID_TIPO_COCINA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE PLATO (
  ID_PLATO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO BIGINT NOT NULL REFERENCES USUARIO(ID_USUARIO),
  ID_CATEGORIA BIGINT NOT NULL REFERENCES CATEGORIA(ID_CATEGORIA),
  ID_TIPO_COCINA BIGINT NOT NULL REFERENCES TIPO_COCINA(ID_TIPO_COCINA),
  NOMBRE VARCHAR(200) NOT NULL,
  DESCRIPCION VARCHAR(1000),
  IMAGEN_URL VARCHAR(500),
  TIEMPO_PREPARACION INT NOT NULL,
  INGREDIENTES VARCHAR(2000) NOT NULL,
  ELABORACION TEXT NOT NULL,
  ESTADO VARCHAR(10) NOT NULL DEFAULT 'OCULTO',
  FECHA_CREACION TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT CK_PLATO_TIEMPO CHECK (TIEMPO_PREPARACION > 0),
  CONSTRAINT CK_PLATO_ESTADO CHECK (ESTADO IN ('PUBLICADO', 'OCULTO'))
);

CREATE TABLE FAVORITO (
  ID_USUARIO BIGINT NOT NULL REFERENCES USUARIO(ID_USUARIO) ON DELETE CASCADE,
  ID_PLATO BIGINT NOT NULL REFERENCES PLATO(ID_PLATO) ON DELETE CASCADE,
  FECHA TIMESTAMP NOT NULL DEFAULT NOW(),
  PRIMARY KEY (ID_USUARIO, ID_PLATO)
);


-- Seguridad en Supabase: se activa RLS (Row Level Security) en todas las tablas.
-- Supabase expone las tablas del esquema público por una API REST con una clave
-- pública (anon key). Sin RLS, cualquiera con esa clave podría leer o modificar los datos.
-- Con RLS activado y sin políticas, la API pública no puede acceder a ninguna tabla.
-- Spring Boot se conecta directamente a PostgreSQL con el usuario "postgres",
-- que se salta RLS, así que la aplicación sigue funcionando igual.
ALTER TABLE USUARIO     ENABLE ROW LEVEL SECURITY;
ALTER TABLE CATEGORIA   ENABLE ROW LEVEL SECURITY;
ALTER TABLE TIPO_COCINA ENABLE ROW LEVEL SECURITY;
ALTER TABLE PLATO       ENABLE ROW LEVEL SECURITY;
ALTER TABLE FAVORITO    ENABLE ROW LEVEL SECURITY;